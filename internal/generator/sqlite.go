package generator

import (
	"bytes"
	"fmt"
	"strings"

	"go.f110.dev/xerrors"

	"go.f110.dev/protoc-ddl/internal/schema"
)

const (
	SQLiteGeneratorVersion = "v0.1"
)

var (
	SQLiteDataTypeMap = map[string]string{
		"TYPE_FLOAT":         "REAL",
		"TYPE_DOUBLE":        "REAL",
		"TYPE_INT32":         "INTEGER",
		"TYPE_INT64":         "INTEGER",
		"TYPE_UINT32":        "INTEGER",
		"TYPE_UINT64":        "INTEGER",
		"TYPE_SINT32":        "INTEGER",
		"TYPE_SINT64":        "INTEGER",
		"TYPE_FIXED32":       "INTEGER",
		"TYPE_FIXED64":       "INTEGER",
		"TYPE_SFIXED32":      "INTEGER",
		"TYPE_SFIXED64":      "INTEGER",
		"TYPE_BOOL":          "INTEGER",
		"TYPE_BYTES":         "BLOB",
		"TYPE_STRING":        "TEXT",
		schema.TimestampType: "DATETIME",
	}
)

// SQLiteGenerator generates DDL for SQLite.
// The column which has the sequence option must be the only primary key of the table, because SQLite allows AUTOINCREMENT
// only for INTEGER PRIMARY KEY. The name of the index must be unique in the database.
type SQLiteGenerator struct{}

func (g SQLiteGenerator) Generate(writer *bytes.Buffer, tables *schema.Messages) error {
	fmt.Fprintf(writer, "-- Generated by SQLite Generator (%s)\n\n", SQLiteGeneratorVersion)

	var err error
	indexNames := make(map[string]string)
	tables.Each(func(table *schema.Message) {
		if err != nil {
			return
		}

		var colLine []string
		colLine, err = g.generateColumnDefinition(table)
		if err != nil {
			return
		}
		if len(table.PrimaryKeys) > 0 && !g.hasSequencePrimaryKey(table) {
			primaryKeys := make([]string, 0, len(table.PrimaryKeys))
			for _, p := range table.PrimaryKeys {
				primaryKeys = append(primaryKeys, fmt.Sprintf("`%s`", p.Name))
			}
			colLine = append(colLine, fmt.Sprintf("\tPRIMARY KEY(%s)", strings.Join(primaryKeys, ",")))
		}

		fmt.Fprintf(writer, "DROP TABLE IF EXISTS `%s`;\n", table.TableName)
		fmt.Fprintf(writer, "CREATE TABLE `%s` (\n", table.TableName)
		writer.WriteString(strings.Join(colLine, ",\n"))
		writer.WriteString("\n);\n")

		for _, i := range table.Indexes {
			idxName := indexName(i)
			if t, ok := indexNames[idxName]; ok {
				err = xerrors.Newf("index %s of %s is already used by %s", idxName, table.TableName, t)
				return
			}
			indexNames[idxName] = table.TableName

			cols := make([]string, 0, i.Columns.Len())
			i.Columns.Each(func(f *schema.Field) {
				cols = append(cols, fmt.Sprintf("`%s`", f.Name))
			})
			indexType := "INDEX"
			if i.Unique {
				indexType = "UNIQUE INDEX"
			}
			fmt.Fprintf(writer, "CREATE %s `%s` ON `%s` (%s);\n", indexType, idxName, table.TableName, strings.Join(cols, ", "))
		}
		writer.WriteString("\n")
	})

	return err
}

func (g SQLiteGenerator) hasSequencePrimaryKey(table *schema.Message) bool {
	return len(table.PrimaryKeys) == 1 && table.PrimaryKeys[0].Sequence
}

func (g SQLiteGenerator) generateColumnDefinition(table *schema.Message) ([]string, error) {
	var err error
	colLine := make([]string, 0)
	table.Fields.Each(func(col *schema.Field) {
		if err != nil {
			return
		}

		nullConstraint := "NOT NULL"
		if col.Null {
			nullConstraint = "NULL"
		}
		columnOpt := ""
		if col.Sequence {
			if !g.hasSequencePrimaryKey(table) || table.PrimaryKeys[0].Name != col.Name {
				err = xerrors.Newf("%s.%s: sequence is allowed only for the column which is the only primary key", table.TableName, col.Name)
				return
			}
			columnOpt += " PRIMARY KEY AUTOINCREMENT"
		}
		if col.Default != "" {
			switch col.Type {
			case "TYPE_INT32", "TYPE_INT64", "TYPE_UINT32", "TYPE_UINT64", "TYPE_SINT32", "TYPE_SINT64":
				columnOpt += fmt.Sprintf(" DEFAULT %s", col.Default)
			default:
				columnOpt += fmt.Sprintf(" DEFAULT '%s'", strings.ReplaceAll(col.Default, "'", "''"))
			}
		}

		colLine = append(colLine, fmt.Sprintf("\t`%s` %s %s%s", col.Name, SQLiteDataTypeMap[col.Type], nullConstraint, columnOpt))
	})

	return colLine, err
}

func indexName(i *schema.Index) string {
	if i.Name != "" {
		return i.Name
	}

	colNames := make([]string, 0, i.Columns.Len())
	i.Columns.Each(func(f *schema.Field) {
		colNames = append(colNames, f.Name)
	})
	return "idx_" + strings.Join(colNames, "_")
}
