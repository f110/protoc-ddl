package generator

import (
	"bytes"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"go.f110.dev/protoc-ddl/internal/schema"
)

func TestSQLiteGenerator(t *testing.T) {
	t.Run("Sequence and indexes", func(t *testing.T) {
		id := &schema.Field{Name: "id", Type: "TYPE_INT64", Sequence: true}
		title := &schema.Field{Name: "title", Type: "TYPE_STRING", Size: 100}
		user := schema.NewMessage(nil, nil)
		user.TableName = "user"
		user.Fields = schema.NewFields([]*schema.Field{
			id,
			{Name: "age", Type: "TYPE_INT32", Default: "20"},
			title,
			{Name: "nickname", Type: "TYPE_STRING", Null: true, Default: "it's"},
			{Name: "score", Type: "TYPE_DOUBLE"},
			{Name: "active", Type: "TYPE_BOOL"},
			{Name: "avatar", Type: "TYPE_BYTES", OptionalType: "long"},
			{Name: "created_at", Type: schema.TimestampType},
		})
		user.PrimaryKeys = []*schema.Field{id}
		user.Indexes = []*schema.Index{
			{Columns: schema.NewFields([]*schema.Field{title}), Unique: true},
			{Name: "idx_by_age", Columns: schema.NewFields([]*schema.Field{user.Fields.Get("age"), title})},
		}

		buf := new(bytes.Buffer)
		err := SQLiteGenerator{}.Generate(buf, schema.NewMessages([]*schema.Message{user}, nil))
		require.NoError(t, err)
		assert.Equal(t, "-- Generated by SQLite Generator (v0.1)\n\n"+
			"DROP TABLE IF EXISTS `user`;\n"+
			"CREATE TABLE `user` (\n"+
			"\t`id` INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,\n"+
			"\t`age` INTEGER NOT NULL DEFAULT 20,\n"+
			"\t`title` TEXT NOT NULL,\n"+
			"\t`nickname` TEXT NULL DEFAULT 'it''s',\n"+
			"\t`score` REAL NOT NULL,\n"+
			"\t`active` INTEGER NOT NULL,\n"+
			"\t`avatar` BLOB NOT NULL,\n"+
			"\t`created_at` DATETIME NOT NULL\n"+
			");\n"+
			"CREATE UNIQUE INDEX `idx_title` ON `user` (`title`);\n"+
			"CREATE INDEX `idx_by_age` ON `user` (`age`, `title`);\n\n",
			buf.String(),
		)
	})

	t.Run("Composite primary key", func(t *testing.T) {
		userId := &schema.Field{Name: "user_id", Type: "TYPE_INT32"}
		blogId := &schema.Field{Name: "blog_id", Type: "TYPE_INT64"}
		like := schema.NewMessage(nil, nil)
		like.TableName = "like"
		like.Fields = schema.NewFields([]*schema.Field{userId, blogId})
		like.PrimaryKeys = []*schema.Field{userId, blogId}

		buf := new(bytes.Buffer)
		err := SQLiteGenerator{}.Generate(buf, schema.NewMessages([]*schema.Message{like}, nil))
		require.NoError(t, err)
		assert.Equal(t, "-- Generated by SQLite Generator (v0.1)\n\n"+
			"DROP TABLE IF EXISTS `like`;\n"+
			"CREATE TABLE `like` (\n"+
			"\t`user_id` INTEGER NOT NULL,\n"+
			"\t`blog_id` INTEGER NOT NULL,\n"+
			"\tPRIMARY KEY(`user_id`,`blog_id`)\n"+
			");\n\n",
			buf.String(),
		)
	})

	t.Run("Sequence in composite primary key", func(t *testing.T) {
		id := &schema.Field{Name: "id", Type: "TYPE_INT64", Sequence: true}
		userId := &schema.Field{Name: "user_id", Type: "TYPE_INT32"}
		blog := schema.NewMessage(nil, nil)
		blog.TableName = "blog"
		blog.Fields = schema.NewFields([]*schema.Field{id, userId})
		blog.PrimaryKeys = []*schema.Field{id, userId}

		err := SQLiteGenerator{}.Generate(new(bytes.Buffer), schema.NewMessages([]*schema.Message{blog}, nil))
		require.Error(t, err)
	})

	t.Run("Duplicated index name", func(t *testing.T) {
		messages := make([]*schema.Message, 0, 2)
		for _, name := range []string{"user", "blog"} {
			title := &schema.Field{Name: "title", Type: "TYPE_STRING"}
			m := schema.NewMessage(nil, nil)
			m.TableName = name
			m.Fields = schema.NewFields([]*schema.Field{title})
			m.Indexes = []*schema.Index{{Columns: schema.NewFields([]*schema.Field{title})}}
			messages = append(messages, m)
		}

		err := SQLiteGenerator{}.Generate(new(bytes.Buffer), schema.NewMessages(messages, nil))
		require.Error(t, err)
	})
}
